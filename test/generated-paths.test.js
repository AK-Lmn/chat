import { expect, test } from 'bun:test';
import { fliskGenerated, runTask } from '../src/loop.js';
import { SYSTEM } from '../src/prompt.js';

test('Flisk generated files are recognised, with the input to change instead', () => {
  expect(fliskGenerated('~/app/services/api/.autogenerated/Dockerfile')).toBe('~/app/services/api/service.json');
  expect(fliskGenerated('~/app/.flisk/.flisk-out/registry.json')).toBe('the service.json files');
  expect(fliskGenerated('~/app/Tiltfile')).toBe('the service.json files');
  expect(fliskGenerated('~/app/TILT_TECH_STACK.star')).toBe('the service.json files');
  expect(fliskGenerated('~/app/.tiltignore')).toBe('the service.json files');
  expect(fliskGenerated('~/app/product_autogenerated_services_list/list.json')).toBe('the service.json files');
  // The user's own code and Flisk's inputs stay writable.
  for (const p of ['~/app/api/src/index.js', '~/app/web/index.html', '~/app/api/service.json', '~/app/api/package.json', '~/app/.flisk/project.json', '~/site/autogenerated-notes.md']) expect(fliskGenerated(p)).toBe(null);
});

test('a write into a generated folder is refused and the model is told what to change', async () => {
  const files = {};
  const computer = {
    start: async () => ({ status: 201, data: { id: 'p1', provider: 'upstash' } }),
    stop: async () => ({ status: 200, data: {} }),
    run: async () => ({ status: 200, data: { exitCode: 0, stdout: '', stderr: '' } }),
    write: async (id, path, content) => ((files[path] = content), { status: 200, data: {} }),
    read: async () => ({ error: 'No such file' }),
  };
  const replies = [
    { text: JSON.stringify({ write: { path: '/home/user/app/api/.autogenerated/Dockerfile', content: 'FROM node:22' } }) },
    { text: JSON.stringify({ write: { path: '~/app/api/src/index.js', content: 'export default 1' } }) },
    { text: '{"say": "Done."}' },
  ];
  const seen = [];
  let i = 0;
  const model = async (messages) => (seen.push(messages.at(-1).content), replies[Math.min(i++, replies.length - 1)]);
  const r = await runTask({ task: 'fix the api', model, computer, publish: async () => ({ url: 'x' }) });
  expect(seen[1]).toContain('generated by Flisk');
  expect(seen[1]).toContain('~/app/api/service.json');
  expect(Object.keys(files)).toEqual(['~/app/api/src/index.js']);
  expect(r.answer).toBe('Done.');
});

test('the prompt tells the model not to write Flisk generated files', () => {
  expect(SYSTEM).toContain('never write into a .autogenerated folder');
});

test('plain questions get a grounded, structured answer, not a short generic one', () => {
  expect(SYSTEM).toContain('Quality of a plain answer');
  expect(SYSTEM).toContain('Never answer in one or two generic sentences');
  expect(SYSTEM).toContain('specific follow-up');
  expect(SYSTEM).not.toContain('Keep plain questions short');
  expect(SYSTEM).not.toContain('ANSWER_STYLE');
});
